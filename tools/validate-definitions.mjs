#!/usr/bin/env node
/*
 * Mirrors WorkflowDefinitionValidator so the JSON definitions can be checked
 * without a .NET toolchain. The C# validator remains authoritative and runs in
 * CI; this exists for fast local feedback and for editors without .NET.
 *
 * Usage: node tools/validate-definitions.mjs [dir]
 */

import { readFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const KNOWN_RESOLVERS = new Set([
  "Requester",
  "Beneficiary",
  "LineManagerOf",
  "DepartmentHeadOf",
  "ProjectManagerOf",
  "CurrentActor",
]);

const NEGATIVE_ACTIONS = new Set(["REJECT", "RETURN", "WRITE_OFF"]);

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const GUARD_FIELD_SCHEMA_PATH = join(SCRIPT_DIR, "guard-field-schema.json");

/**
 * Extracts every field reference from a guard expression -- the JS mirror of
 * WorkflowDefinitionValidator's AST walk, minus the AST: there is no parser
 * on this side, so this works off tokens instead of a tree. String literals
 * are blanked out first so quoted text (e.g. 'Yes') is never mistaken for a
 * field, and an identifier immediately followed by '(' is a guard function
 * call (Abs, Round, ...), not a field, matching GuardParser's own
 * identifier-vs-function-call rule.
 */
function extractGuardFieldNames(guard) {
  const withoutStringLiterals = guard.replace(/'[^']*'/g, "''");
  const fields = new Set();
  const identifierRe = /[A-Za-z_][A-Za-z0-9_]*/g;

  let match;
  while ((match = identifierRe.exec(withoutStringLiterals)) !== null) {
    const name = match[0];
    if (name === "true" || name === "false" || name === "null") continue;

    const rest = withoutStringLiterals.slice(match.index + name.length);
    if (/^\s*\(/.test(rest)) continue; // function call name, not a field

    fields.add(name);
  }

  return fields;
}

/**
 * The schema file is generated by `dotnet build tools/Desicon.Workflow.SchemaExport`
 * (an AfterTargets="Build" step), so a from-scratch checkout without a prior
 * .NET build won't have it yet. Locally that's just a slower feedback loop --
 * degrade gracefully and let the C# WorkflowDefinitionValidator catch a bad
 * guard field at test time instead. In CI there is no excuse: the build step
 * always runs first, so a missing file there means the export step silently
 * broke, and this script must fail loudly rather than pass a check it didn't
 * actually run.
 */
function loadGuardFieldSchema() {
  if (!existsSync(GUARD_FIELD_SCHEMA_PATH)) {
    if (process.env.CI) {
      console.error(
        `\nERROR: ${GUARD_FIELD_SCHEMA_PATH} not found. In CI this file must ` +
          "already exist (produced by `dotnet build tools/Desicon.Workflow.SchemaExport` " +
          "earlier in the pipeline) -- guard-field reachability checks cannot be " +
          "silently skipped here.",
      );
      process.exit(1);
    }

    console.log(
      `\nNOTE: ${GUARD_FIELD_SCHEMA_PATH} not found -- skipping guard-field ` +
        "reachability checks. Run `dotnet build tools/Desicon.Workflow.SchemaExport` " +
        "to generate it (the C# WorkflowDefinitionValidator still runs this check in CI).",
    );
    return null;
  }

  return JSON.parse(readFileSync(GUARD_FIELD_SCHEMA_PATH, "utf8"));
}

function traverse(def, startKey) {
  const visited = new Set([startKey]);
  const queue = [startKey];

  while (queue.length > 0) {
    const current = queue.shift();
    for (const t of def.transitions.filter((x) => x.from === current)) {
      if (!visited.has(t.to)) {
        visited.add(t.to);
        queue.push(t.to);
      }
    }
  }

  return visited;
}

function validate(def, guardFieldSchema) {
  const errors = [];
  const warnings = [];
  const stateKeys = new Set();
  const moduleFields = guardFieldSchema?.[def.moduleKey]
    ? new Set(guardFieldSchema[def.moduleKey])
    : null;

  for (const s of def.states) {
    if (stateKeys.has(s.key)) errors.push(`DUPLICATE_STATE: ${s.key}`);
    stateKeys.add(s.key);
  }

  const initial = def.states.filter((s) => s.type === "initial");
  if (initial.length === 0) errors.push("NO_INITIAL_STATE");
  if (initial.length > 1)
    errors.push(`MULTIPLE_INITIAL_STATES: ${initial.map((s) => s.key).join(", ")}`);

  const terminals = def.states.filter((s) => s.type === "terminal").map((s) => s.key);
  if (terminals.length === 0) errors.push("NO_TERMINAL_STATE");

  for (const key of terminals) {
    if (def.transitions.some((t) => t.from === key))
      errors.push(`TERMINAL_HAS_EXIT: ${key}`);
  }

  for (const t of def.transitions) {
    if (!stateKeys.has(t.from)) errors.push(`UNKNOWN_FROM_STATE: ${t.from} (${t.action})`);
    if (!stateKeys.has(t.to)) errors.push(`UNKNOWN_TO_STATE: ${t.to} (${t.action})`);
    if (!t.action) errors.push(`MISSING_ACTION: ${t.from} -> ${t.to}`);

    if (!t.actor || (!t.actor.role && !t.actor.resolver))
      errors.push(`NO_ACTOR: ${t.action} from ${t.from}`);

    if (t.actor?.resolver && !KNOWN_RESOLVERS.has(t.actor.resolver))
      errors.push(`UNKNOWN_RESOLVER: ${t.actor.resolver} (${t.action})`);

    if (t.guard && !t.guardMessage)
      warnings.push(`GUARD_WITHOUT_MESSAGE: ${t.action} from ${t.from}`);

    if (t.guard && moduleFields) {
      for (const fieldName of extractGuardFieldNames(t.guard)) {
        if (!moduleFields.has(fieldName)) {
          errors.push(`UNKNOWN_GUARD_FIELD: ${fieldName} (${t.action} from ${t.from})`);
        }
      }
    }
  }

  for (const s of def.states) {
    if (!s.sla) {
      if (!s.type || s.type === "normal")
        warnings.push(`STATE_WITHOUT_SLA: ${s.key}`);
      continue;
    }

    if (s.sla.hours <= 0) errors.push(`INVALID_SLA: ${s.key}`);

    if (s.sla.escalateTo && !stateKeys.has(s.sla.escalateTo))
      errors.push(`UNKNOWN_ESCALATION_TARGET: ${s.key} -> ${s.sla.escalateTo}`);

    if (s.sla.reminderEveryHours && s.sla.reminderEveryHours >= s.sla.hours)
      warnings.push(
        `REMINDER_AFTER_BREACH: ${s.key} reminds at ${s.sla.reminderEveryHours}h but breaches at ${s.sla.hours}h`,
      );
  }

  if (initial.length === 1) {
    const reachable = traverse(def, initial[0].key);
    for (const s of def.states)
      if (!reachable.has(s.key)) errors.push(`UNREACHABLE_STATE: ${s.key}`);
  }

  const terminalSet = new Set(terminals);
  for (const s of def.states.filter((x) => x.type !== "terminal")) {
    const reachable = traverse(def, s.key);
    if (![...reachable].some((k) => terminalSet.has(k)))
      errors.push(`DEAD_END_STATE: ${s.key} can never be closed`);
  }

  for (const s of def.states.filter((x) => x.sla && (!x.type || x.type === "normal"))) {
    const outbound = def.transitions.filter((t) => t.from === s.key);
    if (outbound.length > 0 && !outbound.some((t) => NEGATIVE_ACTIONS.has(t.action)))
      warnings.push(`NO_NEGATIVE_PATH: ${s.key} offers no REJECT or RETURN`);
  }

  // ---------------------------------------------------------------
  // Policy values must be in force NOW.
  //
  // GetPolicyValue throws when no row for a key has an EffectiveFrom on or
  // before "as of", and ApplyPaymentMethodPolicy calls it on every draft --
  // so a policy whose earliest EffectiveFrom is in the future does not delay
  // a rule, it stops requests being created at all.
  //
  // That happened: PAYMENT_METHOD_THRESHOLD_NGN carried effectiveFrom
  // 2026-09-01 and no earlier row, and the whole platform refused to create
  // an expense claim or a cash advance. The integration suite missed it
  // because its FakeTimeProvider starts at 2026-09-07 -- the tests ran after
  // the date, production ran before it, and both were behaving correctly.
  //
  // A future-dated row is legitimate and is the documented way to schedule a
  // rate change. It is only an error when nothing covers the present.
  const now = new Date();
  const byKey = new Map();

  for (const p of def.policyValues ?? []) {
    if (!byKey.has(p.key)) byKey.set(p.key, []);
    byKey.get(p.key).push(p);
  }

  for (const [key, rows] of byKey) {
    const effectiveNow = rows.some(
      (r) => !r.effectiveFrom || new Date(r.effectiveFrom) <= now,
    );

    if (!effectiveNow) {
      const earliest = rows
        .map((r) => r.effectiveFrom)
        .sort()[0];
      errors.push(
        `POLICY_NOT_YET_EFFECTIVE: ${key} has no row effective today — ` +
          `earliest effectiveFrom is ${earliest}. Requests cannot be created until then.`,
      );
    }
  }

  return { errors, warnings };
}

const dir = process.argv[2] ?? "modules";
const files = readdirSync(dir).filter((f) => f.endsWith(".workflow.json"));
const guardFieldSchema = loadGuardFieldSchema();

let failed = false;

for (const file of files) {
  const def = JSON.parse(readFileSync(join(dir, file), "utf8"));
  const { errors, warnings } = validate(def, guardFieldSchema);

  console.log(`\n${file}  (${def.moduleKey} — ${def.formCode} Rev ${def.formRevision})`);
  console.log(`  states: ${def.states.length}  transitions: ${def.transitions.length}`);

  for (const w of warnings) console.log(`  WARN   ${w}`);
  for (const e of errors) console.log(`  ERROR  ${e}`);

  if (errors.length === 0) console.log("  OK — no structural errors");
  if (errors.length > 0) failed = true;
}

console.log("");
process.exit(failed ? 1 : 0);
